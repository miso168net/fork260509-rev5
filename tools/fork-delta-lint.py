def find_fake_success_toast(content):
    """B-061：去註解後不得出現 `$message` 的 success 呼叫（U-M 核心交付「假成功 toast」
    防回歸——base-web 無測試 runner、五道閘全看不見這個語意，upstream rebase 解錯即回歸）。
    回 ([去註解後命中行原貌], **未**去註解時的命中數)。★回傳形沿 [`find_bare_t_calls`]：
    「零違規」與「一個都沒看到檔案內容」是兩件事，靠第二欄分辨。四支標的檔現況第二欄
    **恰為 1**（唯一那處字面在 `原行:` 註解裡），呼叫端據此雙向 die：0＝掃描面沒看到檔案
    內容（或標記已消失）、≥2＝多冒出一處被禁字面（toast 被插回來、卻因去註解走偏而沒進
    違規清單——[`strip_ends_open`] 攔的同一病灶之另一半）。
    ★去註解**失效**（退化成 identity）的反方向是恆紅、由 self-test Z3 擋，不需本欄。"""
    raw_lines = content.splitlines()
    # ★第二欄獨立數 raw、不搭 zip：`strip_comments` 的末行若被吃成空字串，join 後尾隨的
    #   `\n` 會被 splitlines 吞掉一行，zip 隨之截短——恰好漏數的就是「被吞在註解態裡的尾段」。
    raw_hits = sum(1 for l in raw_lines if FAKE_TOAST.search(l))
    hits = [raw.strip() for raw, code in zip(raw_lines, strip_comments(content).splitlines())
            if FAKE_TOAST.search(code)]
    return hits, raw_hits


def find_bare_t_calls(content):
    """B-062：`translateBackendMsg` 內每個 `$t(` 呼叫皆須帶 fallback 引數（`$t(key, msg)`
    或 `$t(key, named, msg)`）——退化成 `$t(key)` 時 vue-i18n 對未命中鍵回**查詢鍵本身**、
    畫面顯裸 `backend.*` 鍵（違「未命中 MUST graceful fallback、不得顯裸 key」收窄），而
    typecheck 綠（合法多載）、quickstart 走不到該腿。
    回 ([違規呼叫字面], 已檢查之函式體內 `$t(` 呼叫數)。★回傳形沿 [`find_rogue_tracks`]：
    「零違規」與「一個都沒檢查到」是兩件事，靠 checked 欄分辨——只回清單則守門面整個消失
    （簽名還在但 body 被抽空、或 `$t` 被搬進 helper 而 fallback 在 helper 內被拔掉）時
    照樣回 `[]` 恆綠，與 T069⑤ 對名冊斷言所做的結構性自證同一形（呼叫端 die）。
    ★射程僅該函式體（大括號配平取界）：`translateDetailValue` 的 `$t('backend.common.
    listSeparator')` 單參形合法在案、不得誤傷。
    ★判準＝**末個頂層引數須為該函式首參識別字**（＝後端原文 msg；識別字由簽名現讀、不寫死）。
    兩種退化形一次涵蓋：`$t(key)`（整組拔成單參）與 `$t(key, named)`（三參形只被吃掉末參，
    upstream rebase 解衝突時更像會發生的形）；不需語意推斷第二參是字串還是 named 插值物件。"""
    code = strip_comments(content)
    m = re.search(r"function translateBackendMsg\s*\(\s*([A-Za-z_$][\w$]*)", code)
    if m is None:
        return (["函式 translateBackendMsg（具名首參形）不存在——守門標的結構性缺席"
                 "（同計違規、先查該檔）"], 0)
    fallback = m.group(1)
    # 函式體＝自簽名後首個 { 起、大括號配平（跳過字串常值）到閉合
    i = code.index("{", m.end())
    depth, quote, j = 0, None, i
    while j < len(code):
        c = code[j]
        if quote:
            if c == "\\":
                j += 2
                continue
            if c == quote:
                quote = None
        elif c in "'\"`":
            quote = c
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    body = code[i:j + 1]
    out, checked = [], 0
    for call in re.finditer(r"\$t\s*\(", body):
        checked += 1
        k, depth, quote, args, buf = call.end(), 0, None, [], []
        while k < len(body):
            c = body[k]
            if quote:
                if c == "\\":
                    buf.append(c)
                    k += 1
                    if k < len(body):
                        buf.append(body[k])
                    k += 1
                    continue
                if c == quote:
                    quote = None
                buf.append(c)
            elif c in "'\"`":
                quote = c
                buf.append(c)
            elif c in "([{":
                depth += 1
                buf.append(c)
            elif c in ")]}":
                if depth == 0:
                    break                    # $t 呼叫的閉括號
                depth -= 1
                buf.append(c)
            elif c == "," and depth == 0:    # 頂層逗號＝引數分界
                args.append("".join(buf).strip())
                buf = []
            else:
                buf.append(c)
            k += 1
        args.append("".join(buf).strip())
        if args[-1] != fallback:             # 末個頂層引數不是原文 msg＝fallback 被吃掉
            out.append("$t(" + ", ".join(args) + ")")
    return out, checked


