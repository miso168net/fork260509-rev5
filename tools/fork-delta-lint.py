BASELINE = "example"
CONSTITUTION = os.path.join(REPO, ".specify", "memory", "constitution.md")

MARKER = re.compile(r"原行:\s*(.*\S)\s*$")

# 軌道名抽取（T069②；B-058 實測五種標記形都要吃）：捕 `[rev5-inline` 後首個大寫 token。
# 字元類止於 `(`（用途後綴 (a)/(i)…）、`+`（新增型尾綴）、空白（刀號）與 `]`——即抽出的
# 恆為「剝掉用途後綴與尾綴 + 之後」的裸名，恰是 §III.2 名冊列的形（B-058：不剝就會把
# 合法標記整批誤判為名冊外）。五形＝`NAME+ 刀號`／`NAME(a) 刀號`／`NAME(i)`（無刀號）／
# `NAME 刀號`（.env 裸形、掃描面外但抽取器仍容忍）／名冊側 `**`／`★` 裝飾（由 load_roster 剝）。
TRACK = re.compile(r"\[rev5-inline\s+([A-Z][A-Z0-9-]*)")


def die(msg):
    print(f"[fork-delta-lint] ✗ {msg}", file=sys.stderr)
    sys.exit(2)


def load_roster():
    """T069①：授權軌道名冊＝constitution §III.2 ★軌道 ∪ §III.1 三軌道。

    掃描錨（§III.2 自述）：表格資料列以 `|` 起、跳標題列與分隔列；軌道名於首欄、
    剝 `**` 與 `★` 裝飾。★檔缺席／掃空＝die（fail-loud，絕不默認空名冊放行一切）。
    T069⑤ 三重非 vacuous 斷言亦在此落地（每次執行都跑）：①名冊整體非空
    ②§III.2 ★段貢獻列數 ≥ 4 ③承襲指針散文中本刀不開的兩名（MODAL-WIRING／
    BASE-WEB-DEVPROXY-WIRING）不得被掃進名冊——證掃描面只及表格、不及散文。"""
    if not os.path.isfile(CONSTITUTION):
        die(f"constitution 不存在：{CONSTITUTION}（T069 名冊來源、缺之即無授權判準）")
    roster, s1_rows, s2_rows, section = set(), 0, 0, None
    for line in open(CONSTITUTION, encoding="utf-8").read().splitlines():
        if line.startswith("### III.1"):
            section = 1
            continue
        if line.startswith("### III.2"):
            section = 2
            continue
        if line.startswith(("## ", "### ")):
            section = None
            continue
        if section is None or not line.startswith("|"):
            continue
        cells = line.split("|")
        name = cells[1].strip().strip("*★").strip() if len(cells) > 1 else ""
        # 跳標題列（首欄「軌道」）與分隔列（純 -/: 字元）
        if not name or name == "軌道" or set(name) <= set("-: "):
            continue
        roster.add(name)
        if section == 1:
            s1_rows += 1
        elif section == 2:
            s2_rows += 1
    if not roster:
        die("名冊掃描為空——constitution §III.1/§III.2 表格錨可能被改動（T069⑤ 非空斷言①）")
    if s2_rows < 4:
        die(f"§III.2 ★軌道表僅掃得 {s2_rows} 列（須 ≥4）——表錨或列形被改動（T069⑤ 非空斷言②）")
    # ★§III.1 半邊的同形斷言（final holistic review 補：原三重斷言**全部只約束 §III.2**，
    #   §III.1 三軌道可靜默自名冊掉線而 lint 全綠）。實測失效鏈：把 `### III.1` 改成
    #   `### III-1`（或整表刪除）⇒ roster 由 7 名縮成 4 名、輸出仍宣稱「軌道名皆在名冊」，
    #   直到某刀第一次用 BASE-WEB-ADAPT／BASE-WEB-WRAPPER 開**修改型**標記才報「不在名冊、
    #   須先走 §V.2 Amendment」——指向錯誤修法（該軌道早已授權），真病灶不被指出。
    #   與 .githooks/pre-commit 補 constitution 觸發源所修的是同一個「fail-late 且誤導」病。
    if s1_rows != 3:
        die(f"§III.1 預設可動軌道表掃得 {s1_rows} 列（須恰 3）——表錨或列形被改動；名冊會靜默少收三名而全鏈照綠（T069⑤ 非空斷言③）")
    for absent in ("MODAL-WIRING", "BASE-WEB-DEVPROXY-WIRING"):
        if absent in roster:
            die(f"{absent} 被掃進名冊——它只存在於承襲指針散文（§III.2 表外宣告 2、本刀未開），"
                f"掃描面誤及散文＝名冊失真（T069⑤ 反例斷言）")
    return roster


def find_rogue_tracks(ours_content, roster):
    """T069③：修改型標記（同行含 `原行:`）的軌道名 ∈ 授權名冊斷言＋「同行必含
    `[rev5-inline` token」強制（堵現行漏洞：任何含 `原行:` 的行都算已記錄）。
    回 ([(標記行去空白, 錯因)], 已檢查之修改型標記行數)。★射程僅修改型——新增型
    `NAME+` 不入名冊（§III.2 表外宣告 3、承 ADR 0021 款 1）。"""
    out, checked = [], 0
    for l in ours_content.splitlines():
        if "原行:" not in l:
            continue
        s = l.strip()
        if "[rev5-inline" not in s:
            out.append((s, "缺 [rev5-inline token——裸 `原行:` 不構成合法修改型標記"))
            continue
        checked += 1
        m = TRACK.search(s)
        if not m:
            out.append((s, "抽不出軌道名（標記形制不符 `[rev5-inline <TRACK>…]`）"))
        elif m.group(1) not in roster:
            out.append((s, f"軌道名 {m.group(1)} 不在授權名冊（constitution §III.1/§III.2）"))
    return out, checked


def sh(args, cwd):
    # 清掉 GIT_* env：git hook 會把外層 repo 的 GIT_DIR/GIT_INDEX_FILE 洩漏給子行程，
    # 害對 base-web worktree（.git 為檔）跑 git 抓錯 index（.git/index: Not a directory）。
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True, env=env)


def is_code(line):
    s = line.strip()
    return bool(s) and not s.startswith(("//", "/*", "*", "<!--"))


def norm(line):
    # 去尾端逗號/分號：加新同層條目使前一行多尾逗號，屬新增型副作用、非語意改變（§III「語意被改變」才算修改型）
    return line.strip().rstrip(",;").rstrip()


def find_missing(base_content, ours_content):
    """回傳「基線有、我方既無此行、又無對應原行標記」的上游**原行**（供逐字補回）。
    ★比對用 norm（去尾標點）、輸出保原行原貌（含尾逗號等）。"""
    ours = ours_content.splitlines()
    ours_lines = {norm(l) for l in ours}
    recorded = set()
    for l in ours:
        if "[rev5-inline" not in l:
            continue  # T069③：裸 `原行:`（無 rev5-inline token）不算已記錄——防形制外洗白
        m = MARKER.search(l)
        if m:
            recorded.add(norm(m.group(1)))
    seen = set()
    missing = []
    for raw in base_content.splitlines():
        if not is_code(raw):
            continue
        n = norm(raw)
        if not n or n in ours_lines or n in recorded or n in seen:
            continue
        seen.add(n)
        missing.append(raw.strip())  # 原行原貌（去首尾空白、保尾逗號）
    return missing


def is_generated(content):
    """檔頭 8 行含生成器標記＝機器生成檔（elegant-router／unplugin 等）：fork-delta 由重算保證、
    不手標圈界，故豁免。★限檔頭（避免誤中 hand-written 檔散文裡的『auto generated』字樣——
    如 store/modules/route/index.ts 第 36 行、theme/shared.ts 第 264 行）。"""
    head = "\n".join(content.splitlines()[:8])
    return bool(re.search(r"Generated by|@generated", head))


def _code_of_line(line, closing):
    """單行去註解：回（碼文本, 新 closing 態）。`closing`＝跨行區塊註解的待閉合 token
    （None＝不在註解內）。★逐字元掃描、正確處理跨行 /* */、<!-- --> 之開閉——含『同行
    閉合後緊接碼』（對抗驗證 NF-A：`*/ code` 不再整行丟棄）與『同行連續 /* */ /* …』
    （對抗驗證 NF-C：第二註解 body 不洩為碼）；行註解 // 到行尾（不跨行、closing 不置位）。
    [`_block_code_added`]（新增型圈界掃描）與 [`strip_comments`]（B-061/B-062 語意掃描）
    共用這一份——去註解規則只此一處，兩面不分岔。"""
    rest, code = line, ""
    while rest:
        if closing:                          # 在跨行區塊註解內、找閉合
            k = rest.find(closing)
            if k < 0:
                return code, closing
            rest, closing = rest[k + len(closing):], None
            continue
        cands = [(rest.find(t), t) for t in ("//", "/*", "<!--") if t in rest]
        if not cands:
            return code + rest, None
        i, t = min(cands)
        code += rest[:i]
        if t == "//":
            return code, None                # 行註解到行尾
        closing, rest = ("*/" if t == "/*" else "-->"), rest[i + len(t):]
    return code, closing


def _block_code_added(added):
    """回 added 各『去註解後仍有實質碼』的行（原行原貌）。去註解規則見 [`_code_of_line`]。"""
    out, closing = [], None
    for l in added:
        code, closing = _code_of_line(l, closing)
        if code.strip():
            out.append(l)
    return out


def strip_comments(content):
    """全檔去（跨行）註解後的碼文本（行結構保留、行數不變——命中行可回指原貌）。
    B-061／B-062 的語意掃描面：那幾支檔的 `原行:` 註解裡就有被禁字面，不剝註解即恆紅。"""
    out, closing = [], None
    for l in content.splitlines():
        code, closing = _code_of_line(l, closing)
        out.append(code)
    return "\n".join(out)


def strip_ends_open(content):
    """去註解掃到 EOF 時是否**仍卡在**跨行區塊註解內（`closing` 未歸零）。
    真 .ts／.vue 不可能以未閉合 `/*`／`<!--` 收尾（語法錯、build 當場紅），故此態的唯一
    現實成因＝[`_code_of_line`] **不解析字串常值**：`/*` 或 `<!--` 出現在字串字面裡即置位
    `closing`、把其後全部內容當註解吞掉。那正是 B-061 語意守的恆綠路徑（掃描零命中→rc=0），
    且與「upstream rebase 解錯把 toast 插回來」可在同一次 rebase 同時發生。"""
    closing = None
    for l in content.splitlines():
        _, closing = _code_of_line(l, closing)
    return closing is not None


def _structural_only(line):
    """純結構標點行（}、);、],… 無任何識別碼字元）＝區塊延續、不需獨立圈界（避免對閉合括號誤報）。"""
    return not re.search(r"[0-9A-Za-z_$]", line)


def _block_has_marker(added):
    """change-block 內有無合法 rev5 標記——限『註解行』且含 [rev5-inline（排除字串常值內同名子字串
    的自我認證：對抗驗證 FN2）。"""
    return any(s.startswith(("//", "/*", "*", "<!--")) and "[rev5-inline" in s
               for s in (l.strip() for l in added))


def find_unmarked_additions(base_content, ours_content):
    """回「新增碼 change-block 卻無合法 rev5-inline 標記」之首個實質新增行（供補圈界標記）。★補位
    find_missing（後者驗修改型缺原行）；本函式驗新增型缺圈界，合起來令所有 fork-delta 皆帶標記。
    §III 新增型圈界紀律。

    以 difflib.unified_diff 取差異、按 **change-block**（連續 +/- 行為一塊、context 行〔含空白〕分界）；
    ★只驗『純新增塊』（塊內無任何被移除碼行）——含被移除碼行者＝修改型/替換區塊、由 find_missing
    驗原行、本函式跳過（故 captcha 型『替換邏輯與其原行標記被空白 context 分隔』不誤報）。純新增塊去
    （跨行）註解＋純結構標點行（閉合 } 等＝區塊延續）後仍有實質新增碼卻無合法標記（限註解行、字串
    常值內子字串不算）→報首行。分工：修改型缺原行→find_missing；純新增（新 import/欄位）缺圈界→本函式。
    ★已知可接受殘留（2 輪對抗驗證後定；見 LESSONS）：①與修改型同塊（無 context 分隔）的額外未圈界
    新增歸該塊原行標記涵蓋、不另報（修它會重引入 captcha 型替換誤報張力）；②字串常值內未閉合 /* 之
    後續行罕見被當註解（窄 FN；不做 string-parsing）。假 DEL 洗白被 find_missing『刪行缺原行』兜住。"""
    out = []
    added, removed = [], []
    seen_hunk = False

    def flush():
        if any(is_code(l) for l in removed):
            return                           # 修改型/替換塊（含移除碼）→ 歸 find_missing、本函式跳過
        substantive = [l for l in _block_code_added(added) if not _structural_only(l)]
        if substantive and not _block_has_marker(added):
            out.append(substantive[0].strip())

    for line in difflib.unified_diff(base_content.splitlines(),
                                     ours_content.splitlines(), n=3, lineterm=""):
        if line.startswith("@@"):
            flush(); added, removed = [], []; seen_hunk = True
        elif not seen_hunk:
            continue                         # unified_diff 檔頭 ---/+++（首個 @@ 前）——seen_hunk 旗標
        elif line.startswith("+"):           # 認檔頭，內容以 ++/-- 起首不撞 +++/---（對抗驗證 INT1）
            added.append(line[1:])
        elif line.startswith("-"):
            removed.append(line[1:])
        else:                                # context 行（含空白）＝ change-block 分界
            flush(); added, removed = [], []
    flush()
    return out


