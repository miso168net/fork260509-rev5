def cmd_check(constitution_path):
    self_test()

    # ①-a 憲法列的宣告集
    try:
        with open(constitution_path, encoding="utf-8") as fh:
            text = fh.read()
    except OSError as ex:
        raise GateError(f"讀不到憲法檔（{constitution_path}）：{ex}"
                        f"——授權來源缺席就不能假裝驗過") from ex
    declared = parse_roster_row(text)

    # ①-b 版控裡掛著產物檔頭的檔集
    header_set = scan_generated(os.path.join(REPO_ROOT, BASE_WEB_REL, "src"))

    probe_container()

    # ①-c 外掛實際產出檔集（空沙盒觀測——不預設任何清單）
    box_c = make_sandbox("observe")
    produced = run_plugin(box_c)

    if not produced:
        raise GateError("外掛在空沙盒零產出——外掛設定或 view 樹異常，本閘不能把「沒東西」當成綠")

    problems = []
    header_mismatch, missing = roster_verdict(produced, header_set, declared)
    if header_mismatch:
        problems.append(
            "① 產出檔集 ≠ 帶產物檔頭的版控檔集\n"
            f"    外掛實際產出：{list(produced)}\n"
            f"    版控帶檔頭者：{list(header_set)}\n"
            "    → 多出來的產出檔未進版控／版控多掛了檔頭；兩者必須一一對應")
    if missing:
        problems.append(
            "① 憲法 §III.2 第五列漏列產物檔（漏列一支＝該支完全無守）\n"
            f"    漏列：{missing}\n"
            f"    該列現有路徑：{list(declared)}\n"
            "    → 補進該列的範圍欄（走 §V.2 Amendment），或說明為何該支不受本軌道管")

    # ②重算冪等：種＝版控
    box_a = make_sandbox("idempotent")
    for rel in produced:
        sh(f"mkdir -p '{box_a}/{os.path.dirname(rel)}'")
        push_file(os.path.join(REPO_ROOT, BASE_WEB_REL, *rel.split("/")), f"{box_a}/{rel}")
    run_plugin(box_a)
    for rel, diff in compare_against_worktree(box_a, produced):
        problems.append(
            f"② 重算不冪等：{rel}\n"
            "    → 以版控現況為種重跑外掛後內容變了＝版控內容尚未收斂"
            "（新增／搬移 view 後忘了讓外掛重算、或重算結果沒 commit）\n"
            f"{diff}")

    # ③零手改：種＝上游基線
    baseline_root = os.path.join(REPO_ROOT, BASELINE_REL)
    if not os.path.isdir(baseline_root):
        print(f"[route-artifact-gate] ⤳ ③零手改斷言具名跳過：基線源倉 {BASELINE_REL}/ 缺席"
              f"（跑 bash tools/bootstrap.sh 建置後自動恢復）——★此時「手改產物檔」無人看管",
              file=sys.stderr)
    else:
        seeds_missing = [rel for rel in produced
                         if not os.path.isfile(os.path.join(baseline_root, *rel.split("/")))]
        if seeds_missing:
            raise GateError(f"基線源倉缺產物檔 {seeds_missing}——上游結構變動？"
                            f"③ 斷言的種子不完整就不能宣稱驗過")
        box_b = make_sandbox("no-hand-edit")
        for rel in produced:
            sh(f"mkdir -p '{box_b}/{os.path.dirname(rel)}'")
            push_file(os.path.join(baseline_root, *rel.split("/")), f"{box_b}/{rel}")
        run_plugin(box_b)
        for rel, diff in compare_against_worktree(box_b, produced):
            problems.append(
                f"③ 產物檔遭手改：{rel}\n"
                "    → 以**上游基線**為種重算的結果與版控不符；產物檔禁止手改"
                "（憲法 §III.2 第五列產物檔紀律），要改請改 view 樹或外掛設定後重算\n"
                f"{diff}")

    sh(f"rm -rf '{SANDBOX_ROOT}'")

    if problems:
        print("[route-artifact-gate] ✗ 路由產物四檔守門不通過：", file=sys.stderr)
        for p in problems:
            print("  " + p.replace("\n", "\n  "), file=sys.stderr)
        return 1

    print(f"[route-artifact-gate] ✓ 產出檔集 {len(produced)} 支對賬憲法第五列與產物檔頭；"
          f"重算冪等（種＝版控）與零手改（種＝基線）兩道皆 byte 相等（self-test 過）")
    return 0


