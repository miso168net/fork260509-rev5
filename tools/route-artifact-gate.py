BASELINE_REL = "fork260509-soybean-admin-base"

# 憲法 §III.2 表中的目標列（軌道名×用途識別符）——ADR 0040 款三所開之第五條 ★ 軌道。
TRACK_NAME = "BASE-WEB-MANAGE-PAGE-WIRING"
TRACK_PURPOSE = "(i)"

# 產物檔的辨識檔頭（外掛自己寫的；`fork-delta-lint.py` 亦以同字樣豁免手標）。
GENERATED_HEADER = "Generated by elegant-router"
GENERATED_HEADER_MAX_LINE = 8

COMPOSE = ["docker", "compose", "-f", "docker-compose.yml", "-f", "docker-compose.dev.yml"]
BASE_WEB_EXEC = COMPOSE + ["exec", "-T", "base-web"]

START_HINT = "docker compose -f docker-compose.yml -f docker-compose.dev.yml up -d --wait"

# 容器內沙盒根（每道斷言各自一顆、跑完即刪）。
SANDBOX_ROOT = "/tmp/route-artifact-gate"

# 沙盒內的 node 執行器：載入 rev5 **現行**外掛設定（`build/plugins/router.ts`，經 node 型別剝除
# 直接吃 TS），讓外掛以沙盒為 cwd 產出，再等檔案系統靜止後印出它實際寫了哪些檔。
# ★設定不在本檔重抄一份：抄一份就等於多一個會漂移的真相源，而本閘要驗的正是「外掛照設定
#   算出來的東西」。cwd 即外掛的輸出根（`dtsDir` 等預設路徑相對 cwd 解析）。
NODE_RUNNER = r"""
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();

// 只走真目錄與真檔（沙盒的 src/views、src/layouts、node_modules 是 symlink，一律不下探）
function walk(dir, base, out) {
  for (const name of fs.readdirSync(dir).sort()) {
    const abs = path.join(dir, name);
    const rel = base ? `${base}/${name}` : name;
    const st = fs.lstatSync(abs);
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) walk(abs, rel, out);
    else if (st.isFile()) out[rel] = `${st.size}:${st.mtimeMs}`;
  }
}

function snap() {
  const out = {};
  if (fs.existsSync(path.join(root, 'src'))) walk(path.join(root, 'src'), 'src', out);
  return out;
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

const t0 = Date.now();
const mod = await import('/app/build/plugins/router.ts');
mod.setupElegantRouter();   // ★產出是建構子的副作用，外掛未曝出可 await 的 promise

// 等到「檔案都出現且都被本輪重寫過（mtime ≥ t0）、且連續三次快照無變化」為止。
// 純睡固定秒數在慢機器上會取到寫到一半的內容——那種失敗看起來會像 flaky。
let prev = null;
let stable = 0;
let ok = false;
const deadline = Date.now() + 90000;
while (Date.now() < deadline) {
  await sleep(250);
  const cur = snap();
  const names = Object.keys(cur);
  const fresh = names.length > 0 && names.every(n => Number(cur[n].split(':')[1]) >= t0);
  const json = JSON.stringify(cur);
  if (fresh && json === prev) {
    stable += 1;
    if (stable >= 3) { ok = true; break; }
  } else {
    stable = 0;
  }
  prev = json;
}
if (!ok) {
  console.error('[runner] 外掛產出未在 90s 內靜止——沙盒狀態：' + prev);
  process.exit(3);
}
console.log('__FILES__' + JSON.stringify(Object.keys(JSON.parse(prev))));
"""


class GateError(Exception):
    """環境不可用／前提不成立——rc=2（與「檢查判定為紅」的 rc=1 分流）。"""


# ── 憲法 §III.2 表列解析 ────────────────────────────────────────────────────────

# 花括號群組：`src/router/elegant/{imports,routes,transform}.ts`
_RE_BRACE = re.compile(r"^(.*?)\{([^{}]+)\}(.*)$")
# 範圍欄內的反引號路徑字面（限 src/ 起首、含副檔名——避免抓到散文裡的其他反引號片語）
_RE_PATH = re.compile(r"`(src/[^`]+?\.(?:ts|vue|d\.ts))`")


def expand_braces(spec):
    """`a/{b,c}.ts` → ['a/b.ts', 'a/c.ts']；無花括號即原樣單元素。"""
    m = _RE_BRACE.match(spec)
    if not m:
        return [spec]
    head, body, tail = m.group(1), m.group(2), m.group(3)
    out = []
    for piece in body.split(","):
        out.extend(expand_braces(f"{head}{piece.strip()}{tail}"))
    return out


def parse_roster_row(text, track=TRACK_NAME, purpose=TRACK_PURPOSE):
    """自憲法全文抽出目標軌道列的**範圍欄**路徑集（brace 展開、去重排序）。

    找不到該列＝raise GateError（憲法被改名／該列被刪時 fail-loud，不得靜默回空集合——
    回空集合會讓 `G_a ⊆ G_c` 恆假之外的所有斷言失去意義，而空集合看起來像「沒東西要驗」）。
    """
    for line in text.splitlines():
        s = line.strip()
        if not s.startswith("|") or track not in s:
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if len(cells) < 3:
            continue
        if purpose not in cells[1]:
            continue
        paths = []
        for spec in _RE_PATH.findall(cells[2]):
            paths.extend(expand_braces(spec))
        if not paths:
            raise GateError(f"憲法 §III.2 之 {track}{purpose} 列找到了，但範圍欄抽不出任何檔案路徑"
                            f"——欄位形制被改過？")
        return tuple(sorted(set(paths)))
    raise GateError(f"憲法 §III.2 找不到軌道 {track} 的用途 {purpose} 那一列"
                    f"——軌道被改名／撤銷？本閘的授權來源即該列，找不到就不能假裝驗過")


# ── 產物檔頭掃描 ───────────────────────────────────────────────────────────────

def has_generated_header(path):
    """檔頭前 N 行含產物檔頭字樣（限檔頭——避免誤中散文裡提到該字樣的手寫檔）。"""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for idx, line in enumerate(fh):
                if idx >= GENERATED_HEADER_MAX_LINE:
                    return False
                if GENERATED_HEADER in line:
                    return True
    except OSError:
        return False
    return False


def scan_generated(src_root):
    """`<base-web>/src/**` 底下帶產物檔頭的檔案（回相對 base-web 的 posix 路徑、排序）。"""
    out = []
    for dirpath, dirnames, filenames in os.walk(src_root):
        dirnames.sort()
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            if has_generated_header(full):
                rel = os.path.relpath(full, os.path.dirname(src_root))
                out.append(rel.replace(os.sep, "/"))
    return tuple(sorted(out))


# ── 容器操作 ───────────────────────────────────────────────────────────────────

def _run(argv, stdin_bytes=None):
    return subprocess.run(argv, input=stdin_bytes, capture_output=True, cwd=REPO_ROOT)


def probe_container():
    """確認 dev stack 的 base-web 容器可用；不可用＝GateError（附啟動命令）。"""
    try:
        proc = _run(BASE_WEB_EXEC + ["sh", "-c", "test -d /app/node_modules/@elegant-router/vue"])
    except OSError as ex:
        raise GateError(f"無法執行 docker（{ex}）——本閘須在 dev stack 內跑外掛：{START_HINT}")
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or b"").decode("utf-8", "replace").strip()
        raise GateError(f"base-web 容器不可用或缺 @elegant-router/vue（{detail or proc.returncode}）"
                        f"——請先啟動 dev stack：{START_HINT}")


def sh(script):
    """在 base-web 容器內跑一段 sh；非零即 GateError（帶原始輸出）。"""
    proc = _run(BASE_WEB_EXEC + ["sh", "-c", script])
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or b"").decode("utf-8", "replace").strip()
        raise GateError(f"容器內命令失敗（rc={proc.returncode}）：{detail}")
    return proc.stdout.decode("utf-8", "replace")


def push_file(host_path, container_path):
    """host → 容器逐 byte 送檔（沙盒種子用）。"""
    with open(host_path, "rb") as fh:
        payload = fh.read()
    proc = _run(BASE_WEB_EXEC + ["sh", "-c", f"cat > '{container_path}'"], stdin_bytes=payload)
    if proc.returncode != 0:
        detail = (proc.stderr or b"").decode("utf-8", "replace").strip()
        raise GateError(f"送檔至容器失敗（{container_path}）：{detail}")


def make_sandbox(name):
    """建一顆乾淨沙盒：src/views、src/layouts、node_modules 皆 symlink 回 /app（唯讀取用）。"""
    box = f"{SANDBOX_ROOT}/{name}"
    sh(f"rm -rf '{box}' && mkdir -p '{box}/src' && "
       f"ln -s /app/src/views '{box}/src/views' && "
       f"ln -s /app/src/layouts '{box}/src/layouts' && "
       f"ln -s /app/node_modules '{box}/node_modules'")
    return box


def run_plugin(box):
    """在沙盒內跑一次外掛 → 回它實際寫出的檔案相對路徑（相對沙盒根，如 `src/…`）。"""
    runner = f"{box}/__gate-runner.mjs"
    proc = _run(BASE_WEB_EXEC + ["sh", "-c", f"cat > '{runner}'"],
                stdin_bytes=NODE_RUNNER.encode("utf-8"))
    if proc.returncode != 0:
        raise GateError("寫入沙盒 runner 失敗")
    proc = _run(BASE_WEB_EXEC + ["sh", "-c", f"cd '{box}' && node __gate-runner.mjs"])
    out = proc.stdout.decode("utf-8", "replace")
    err = proc.stderr.decode("utf-8", "replace")
    if proc.returncode != 0:
        raise GateError(f"沙盒內跑外掛失敗（rc={proc.returncode}）：{(err or out).strip()}")
    for line in out.splitlines():
        if line.startswith("__FILES__"):
            return tuple(sorted(json.loads(line[len("__FILES__"):])))
    raise GateError(f"沙盒 runner 未回報產出檔集：{out.strip()}｜{err.strip()}")


def _container_sh(script):
    """在 base-web 容器內跑一段 sh → `(rc, stdout)`；本閘 byte 比對的**生產執行面**。"""
    proc = _run(BASE_WEB_EXEC + ["sh", "-c", script])
    return proc.returncode, proc.stdout.decode("utf-8", "replace")


def _host_sh(script):
    """同形但跑在 host——★**僅 self-test 用**：讓比對邏輯能在暫存樹上實跑紅綠兩路，
    毋須 docker、毋須動 repo 內任何真檔。"""
    proc = subprocess.run(["sh", "-c", script], capture_output=True)
    return proc.returncode, proc.stdout.decode("utf-8", "replace")


def roster_verdict(produced, header_set, declared):
    """①產出檔集對賬的**判定核心** → `(檔頭集不符: bool, 憲法漏列: list)`。

    ★抽成一支函式的唯一理由：這兩道判定若在 `cmd_check` 與 self-test 各寫一份，改壞生產面
    那份時 self-test 走的是自己那份、照樣全綠（審查實暴的形）。生產面與 self-test C 一律
    呼叫本函式，改壞這裡兩邊同時紅。訊息組裝留在呼叫端——判定與措辭分離，措辭改動不會
    讓 self-test 需要跟著改。
    """
    return set(produced) != set(header_set), [p for p in produced if p not in declared]


def compare_against_worktree(box, rels, worktree_root="/app", exec_sh=_container_sh):
    """逐支比對沙盒產出 vs 版控；回不一致的 `[(rel, diff)]`。

    `worktree_root`／`exec_sh` **可注入**，預設即生產面（容器內 `/app`＝base-web worktree）。
    ★兩參數存在的唯一理由是讓 self-test F 段能實跑本函式本身：守門的紅路徑若沒被任何測試
    走過，它是否攔得住就純屬宣稱（ADR 0024 決定①）。生產呼叫端一律不帶這兩個參數。
    """
    bad = []
    for rel in rels:
        rc, _ = exec_sh(f"cmp -s '{worktree_root}/{rel}' '{box}/{rel}'")
        if rc != 0:
            _, diff = exec_sh(f"diff -u '{worktree_root}/{rel}' '{box}/{rel}' | head -40")
            bad.append((rel, diff))
    return bad


