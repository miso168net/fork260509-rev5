def self_test():
    """離線紅綠成對。失敗即 AssertionError（每次 check 連帶跑、防恆綠）。"""
    # A 花括號展開
    assert expand_braces("src/router/elegant/{imports,routes,transform}.ts") == [
        "src/router/elegant/imports.ts", "src/router/elegant/routes.ts",
        "src/router/elegant/transform.ts"], "self-test A：花括號群組展開錯"
    assert expand_braces("src/typings/app.d.ts") == ["src/typings/app.d.ts"], \
        "self-test A：無花括號應原樣"

    # B 正常列：抽得出七支（含三支非產物檔——`⊆` 上界的來源）
    declared = parse_roster_row(FIXTURE_TABLE)
    assert declared == tuple(sorted((
        "src/locales/langs/en-us.ts", "src/locales/langs/zh-cn.ts", "src/typings/app.d.ts",
        "src/router/elegant/imports.ts", "src/router/elegant/routes.ts",
        "src/router/elegant/transform.ts", "src/typings/elegant-router.d.ts"))), \
        f"self-test B：範圍欄路徑集抽錯，實得 {declared}"
    # ★「正常列不該有漏列」不在此另寫一份判定式——那是 C-1 的事，且由生產面同一支
    #   `roster_verdict` 判（判定式散成兩份，改壞生產面時 self-test 會照樣綠）。

    # C ★變異一：憲法該列**少列一支**產物檔 → 漏列偵測必紅。
    #   ★三小段一律呼叫**生產面同一支** `roster_verdict`——self-test 若另寫一份判定式，生產面
    #   那份被改壞時本段照樣全綠（等同沒測）。紅綠成對：C-1 正常列判綠、C-2 憲法漏列一支
    #   判紅、C-3 產出檔集與產物檔頭集不符判紅。
    verdict = roster_verdict(PRODUCED_FIXTURE, PRODUCED_FIXTURE, declared)
    assert verdict == (False, []), f"self-test C-1：正常列且檔頭集相符卻判紅（本閘會恆紅），實得 {verdict}"

    mut_declared = parse_roster_row(FIXTURE_TABLE.replace("／`src/typings/elegant-router.d.ts`", ""))
    verdict = roster_verdict(PRODUCED_FIXTURE, PRODUCED_FIXTURE, mut_declared)
    assert verdict == (False, ["src/typings/elegant-router.d.ts"]), \
        f"self-test C-2：憲法少列一支未被抓到（漏列＝該支完全無守），實得 {verdict}"

    verdict = roster_verdict(PRODUCED_FIXTURE, PRODUCED_FIXTURE[:-1], declared)
    assert verdict == (True, []), \
        f"self-test C-3：產出檔集 ≠ 帶產物檔頭的版控檔集未被抓到，實得 {verdict}"

    # D 目標列不存在（軌道被改名／撤銷）＝fail-loud，不得靜默回空集合
    for broken in (FIXTURE_TABLE.replace(TRACK_NAME, "SOME-OTHER-TRACK"),
                   FIXTURE_TABLE.replace("| (i) IP 規則管理頁進場 |", "| (ix) 別的用途 |")):
        try:
            parse_roster_row(broken)
        except GateError:
            pass
        else:  # pragma: no cover - 只有守門壞掉才會走到
            raise AssertionError("self-test D：目標列不存在時未 fail-loud")

    # E 範圍欄零路徑（欄位形制被改壞）＝fail-loud
    try:
        parse_roster_row(FIXTURE_TABLE.replace(
            "`src/locales/langs/{en-us,zh-cn}.ts`（各 1 塊）／`src/typings/app.d.ts`（1 塊）／"
            "`src/router/elegant/{imports,routes,transform}.ts`／`src/typings/elegant-router.d.ts`"
            "（後四支＝路由外掛產物、不標記）", "見下方散文"))
    except GateError:
        pass
    else:  # pragma: no cover
        raise AssertionError("self-test E：範圍欄零路徑時未 fail-loud")

    # F ★變異二：產物檔手改一行 → 第②③道的 byte 比對必紅。
    #   ★這裡**實跑生產函式 `compare_against_worktree`**（注入暫存工作樹根與 host sh 執行面），
    #   紅綠成對：先證兩側逐位相同時判綠（本閘不是恆紅品），再手改「工作樹側」一行——那正是
    #   「有人直接編輯產物檔、重算側不動」的形——證其判紅且 diff 指得出改了什麼。
    #   ★不寫成「另比一次 bytes」：那只斷言兩個建構即不同的字串不相等，守門整支失效也照過
    #   （ADR 0024 決定①所禁的 vacuous 形）。端到端形＝真跑第③道（種＝基線），見 cmd_check。
    with tempfile.TemporaryDirectory() as tmp:
        worktree = os.path.join(tmp, "worktree")
        box = os.path.join(tmp, "box")
        rel = "src/typings/elegant-router.d.ts"
        body = ("// Generated by elegant-router\n"
                "export type RouteKey = 'manage_ip-rule' | 'manage_role';\n")
        for root in (worktree, box):
            os.makedirs(os.path.join(root, os.path.dirname(rel)))
            with open(os.path.join(root, rel), "w", encoding="utf-8") as fh:
                fh.write(body)
        assert compare_against_worktree(box, (rel,), worktree, _host_sh) == [], \
            "self-test F：兩側逐位相同卻報不一致——本閘會恆紅，等同無用"

        with open(os.path.join(worktree, rel), "w", encoding="utf-8") as fh:
            fh.write(body.replace("'manage_ip-rule'", "'manage_ipRule'"))
        bad = compare_against_worktree(box, (rel,), worktree, _host_sh)
        assert [r for r, _ in bad] == [rel], \
            f"self-test F：產物檔手改一行未被抓到（第②③道等同不存在），實得 {bad}"
        assert "manage_ipRule" in bad[0][1], \
            f"self-test F：判紅了但 diff 指不出改動內容（報紅無從追查），實得 {bad[0][1]!r}"

        # G 產物檔頭辨識：限檔頭 N 行內、且散文提及不算
        assert has_generated_header(os.path.join(box, rel)), "self-test G：檔頭第 1 行有字樣卻判否"
        late = os.path.join(tmp, "late.ts")
        with open(late, "w", encoding="utf-8") as fh:
            fh.write("\n" * GENERATED_HEADER_MAX_LINE + f"// {GENERATED_HEADER}\n")
        assert not has_generated_header(late), "self-test G：檔頭窗外的字樣不該算產物檔"


def main(argv):
    args = argv[1:]
    constitution = os.path.join(REPO_ROOT, CONSTITUTION_REL)
    if "--constitution" in args:
        idx = args.index("--constitution")
        if idx + 1 >= len(args):
            print("--constitution 需帶路徑", file=sys.stderr)
            return 64
        constitution = args[idx + 1]
        del args[idx:idx + 2]
    cmd = args[0] if args else "check"
    if cmd == "test":
        self_test()
        print("[route-artifact-gate] ✓ self-test 過（花括號展開／列定位／"
              "★憲法少列一支必紅＋產物檔頭集不符必紅〔實跑 roster_verdict、相符時判綠成對〕／"
              "目標列缺席 fail-loud／範圍欄零路徑 fail-loud／"
              "★產物檔手改一行必紅〔實跑 compare_against_worktree、相同時判綠成對〕／檔頭窗）")
        return 0
    if cmd != "check":
        print(f"用法：{argv[0]} [check|test] [--constitution <path>]", file=sys.stderr)
        return 64
    try:
        return cmd_check(constitution)
    except GateError as ex:
        print(f"[route-artifact-gate] ✗ 環境／前提不成立：{ex}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
